# 홈페이지는 정의·근거·해석·서비스 연결까지 담으므로 한 칸씩 더 든다.
# 두 배까지 늘릴 이유는 없다 — 같은 근거를 쓰는 글이다.
CHANNEL_MORE = {
    "naver": {"sections": 0, "covers": 0, "claims": 0, "chars": 1.0},
    "site":  {"sections": 1, "covers": 2, "claims": 1, "chars": 1.25},
}


def need(article_type: str, channel: str = "naver") -> dict:
    """이 유형·채널이 담아야 할 최소치.

    유형이 기본을 정하고 채널이 보정한다. 채널마다 표를 따로 두면 같은
    값을 두 곳에서 고치게 된다.
    """
    base = NEED.get(article_type) or NEED["정보형"]
    more = CHANNEL_MORE.get(channel) or CHANNEL_MORE["naver"]
    lo, hi = base["chars"]
    return {
        "sections": base["sections"] + more["sections"],
        "covers": base["covers"] + more["covers"],
        "claims": base["claims"] + more["claims"],
        "chars": (round(lo * more["chars"]), round(hi * more["chars"])),
    }


def for_outline(article_type: str, channel: str = "naver") -> dict | None:
    """구조 단계가 프롬프트에 실어 보낼 조각.

    **소제목 목록과 고정 흐름을 넘기지 않는다.** 예전에는 유형 골격을 통째로
    실었다 — 섹션 다섯 개가 제목과 covers 까지 다 적힌 채로. "참고자료" 라고
    적어 두어도 그건 참고자료가 아니라 **채우기 틀**이고, 실제로 후보들이
    전부 그 흐름으로 수렴했다. 허용된 변화가 "어디를 합치고 나눌까" 뿐이었다.

    지금은 **무엇을 해내야 하는지**만 넘긴다. 어떤 순서로 할지는 질문과
    확정된 명제가 정한다.

        purpose      이 유형이 독자에게 해 줘야 하는 것
        must_have    빠지면 이 유형이 성립하지 않는 것
        moves        자주 쓰는 전개. **예시지 목록이 아니다**
        avoid        이 유형에서 하지 않는 것

    `common.flow` · `common.section_count` 도 안 넘긴다. 섹션 수는 채널
    프롬프트가 이미 권하고(홈페이지 4~7, 네이버 3~5) 공통이 "4~5개" 를 또
    말하면 채널 규칙이 무력해진다.

    이미지 계획은 남긴다. 어느 자리에 표가 필요한지는 그 자리에 무엇이
    들어가는지 정한 다음에 알 수 있어서, 나눠 놓으면 사람이 두 화면을 오가며
    같은 판단을 두 번 한다. 다만 "무엇을 어디에" 까지고 어떻게 그릴지는
    이미지를 실제로 만드는 시점 일이다.
    """
    t = TYPES.get(article_type)
    if not t:
        return None
    return {
        "purpose": t.get("purpose", ""),
        "must_have": _must_have(t),
        # 이 유형·채널이 담아야 할 최소치. 부르는 쪽이 채널을 넣는다.
        "need": need(article_type, channel),
        # 이 유형에서 자주 쓰는 전개. 골라 쓰거나 안 써도 된다.
        "moves": _moves(t),
        "avoid": (t.get("notes") or [])[:3],
        "image": deepcopy(t.get("image") or {}),
        "blocks": deepcopy(t.get("blocks") or {}),
    }


def _must_have(t) -> list[str]:
    """빠지면 이 유형이 성립하지 않는 것.

    **"무엇에 답해야 하는가" 를 준다.** 섹션 제목을 그대로 주면 그것이
    소제목이 되어 버린다.

    예전에는 `focus` 와 `question` 을 옮겼는데 너무 추상적이었다 —
    "동일한 기준에 따른 비교" 만으로는 무엇이 빠졌는지 사람도 코드도
    알 수 없다. 비교형인데 **같은 기준이 없으면 비교가 아니다.**
    """
    out = list(t.get("must") or [])
    if t.get("question"):
        out.append(f"독자의 \"{t['question']}\" 에 답이 남아야 한다")
    return out


def _moves(t) -> list[str]:
    """자주 쓰는 전개 조각. 순서가 아니라 후보다.

    flow 를 화살표 한 줄로 주면 그 순서를 그대로 쓴다. 조각으로 흩어 두면
    골라 쓰거나 순서를 바꾸기 쉽다.
    """
    flow = t.get("flow") or ""
    return [x.strip() for x in flow.split("→") if x.strip()]


def for_write(article_type: str) -> dict | None:
    """본문 작성이 프롬프트에 실어 보낼 조각.

    sections·flow·image 는 뺀다. 구조는 6단계에서 이미 확정됐으므로,
    골격을 다시 실으면 모델이 확정된 소제목 대신 골격 쪽으로 글을 끌고 간다.
    남기는 것은 "이 유형이 무엇을 하려는 글인가" 와 "어떤 표현을 쓰고 피하는가"다.

    blocks 를 프롬프트에 직접 적지 않고 여기 둔 이유는 6단계 골격과 같다.
    write.md 에 여섯 유형 규칙을 다 넣으면 쓰지도 않을 다섯이 매 호출에 실리고,
    모델이 다른 유형 규칙으로 샌다.
    """
    t = TYPES.get(article_type)
    if not t:
        return None
    keep = ("purpose", "question", "focus", "notes", "blocks")
    return {k: deepcopy(t[k]) for k in keep if k in t}


def sections(article_type: str) -> list[str]:
    """권장 소제목만. 키 없이 돌 때의 구조안으로 쓴다."""
    t = TYPES.get(article_type)
    return [s["title"] for s in t["sections"]] if t else []
